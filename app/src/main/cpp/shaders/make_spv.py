#!/usr/bin/env python3
"""Turns the SPIR-V of the CAS shaders into cas_spv.h:  make_spv.py cas.vert.spv cas.frag.spv cas_spv.h
The .spv files come from:  glslangValidator -V --target-env vulkan1.0 cas.vert / cas.frag"""
import struct, sys
vs, fs, out = sys.argv[1:4]
def arr(name, path):
    b = open(path, "rb").read()
    assert len(b) % 4 == 0 and struct.unpack("<I", b[:4])[0] == 0x07230203, "not SPIR-V: " + path
    w = struct.unpack("<%dI" % (len(b) // 4), b)
    rows = [", ".join("0x%08x" % x for x in w[i:i + 8]) for i in range(0, len(w), 8)]
    return "static const uint32_t %s[] = {\n    %s\n};\n" % (name, ",\n    ".join(rows))
open(out, "w").write("/* generated by shaders/make_spv.py from shaders/cas.vert and shaders/cas.frag - do not edit */\n"
                     "#include <stdint.h>\n" + arr("cas_vs_spv", vs) + arr("cas_fs_spv", fs))
