#!/usr/bin/env python3
"""Turns the SPIR-V of a vertex/fragment shader pair into a header:  make_spv.py x.vert.spv x.frag.spv x_spv.h [prefix]
The arrays are named <prefix>_vs_spv and <prefix>_fs_spv (prefix defaults to cas).
The .spv files come from:  glslangValidator -V --target-env vulkan1.0 cas.vert / cas.frag"""
import struct, sys
# Several arrays at once:  make_spv.py --arrays out.h name=file.spv name2=file2.spv ...
if sys.argv[1] == "--arrays":
    out = sys.argv[2]
    text = "/* generated by shaders/make_spv.py --arrays - do not edit */\n#include <stdint.h>\n"
    for a in sys.argv[3:]:
        name, path = a.split("=", 1)
        b = open(path, "rb").read()
        assert len(b) % 4 == 0 and struct.unpack("<I", b[:4])[0] == 0x07230203, "not SPIR-V: " + path
        w = struct.unpack("<%dI" % (len(b) // 4), b)
        rows = [", ".join("0x%08x" % x for x in w[i:i + 8]) for i in range(0, len(w), 8)]
        text += "static const uint32_t %s[] = {\n    %s\n};\n" % (name, ",\n    ".join(rows))
    open(out, "w").write(text)
    sys.exit(0)
vs, fs, out = sys.argv[1:4]
prefix = sys.argv[4] if len(sys.argv) > 4 else "cas"
def arr(name, path):
    b = open(path, "rb").read()
    assert len(b) % 4 == 0 and struct.unpack("<I", b[:4])[0] == 0x07230203, "not SPIR-V: " + path
    w = struct.unpack("<%dI" % (len(b) // 4), b)
    rows = [", ".join("0x%08x" % x for x in w[i:i + 8]) for i in range(0, len(w), 8)]
    return "static const uint32_t %s[] = {\n    %s\n};\n" % (name, ",\n    ".join(rows))
open(out, "w").write("/* generated by shaders/make_spv.py from shaders/%s.vert and shaders/%s.frag - do not edit */\n"
                     "#include <stdint.h>\n" % (prefix, prefix) + arr(prefix + "_vs_spv", vs) + arr(prefix + "_fs_spv", fs))
