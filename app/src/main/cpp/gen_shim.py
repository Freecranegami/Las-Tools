#!/usr/bin/env python3
"""Generates vkshim_gen.c: a library exporting every Vulkan command as a tiny
forwarding stub. The stubs jump through a table that vkshim_bind() fills in with
the functions of an already-opened Vulkan loader (the one using the custom driver)."""
import os
import re
import sys

inc, out = sys.argv[1], sys.argv[2]

names = []
seen = set()
for fn in ("vulkan_core.h", "vulkan_android.h"):
    path = os.path.join(inc, fn)
    if not os.path.exists(path):
        if fn == "vulkan_core.h":
            sys.exit("missing " + path)
        continue
    text = open(path, encoding="utf-8", errors="replace").read()
    for m in re.finditer(r"VKAPI_CALL\s+(vk[A-Za-z0-9_]+)\s*\(", text):
        n = m.group(1)
        if n not in seen:
            seen.add(n)
            names.append(n)

if len(names) < 100:
    sys.exit("only found %d Vulkan functions in %s" % (len(names), inc))

lines = []
lines.append("/* generated by gen_shim.py - do not edit */")
lines.append("#include <stddef.h>")
lines.append("#include <stdlib.h>")
lines.append("#include <stdint.h>")
lines.append("#include <dlfcn.h>")
lines.append("#include <android/log.h>")
lines.append("")
lines.append("#define VKSHIM_COUNT %d" % len(names))
lines.append("")
lines.append('__attribute__((visibility("hidden"), used)) void *vkshim_table[VKSHIM_COUNT];')
lines.append("")
lines.append("static const char *const vkshim_names[VKSHIM_COUNT] = {")
for n in names:
    lines.append('    "%s",' % n)
lines.append("};")
lines.append("")
lines.append("#define VKSHIM_STUB(off, name) \\")
lines.append('    __attribute__((naked, visibility("default"))) void name(void) { \\')
lines.append("        __asm__ volatile( \\")
lines.append('            "adrp x16, vkshim_table + " #off "\\n\\t" \\')
lines.append('            "ldr x16, [x16, :lo12:vkshim_table + " #off "]\\n\\t" \\')
lines.append('            "br x16\\n\\t"); \\')
lines.append("    }")
lines.append("")
for i, n in enumerate(names):
    lines.append("VKSHIM_STUB(%d, %s)" % (i * 8, n))
lines.append("")
lines.append("static void vkshim_missing(void) {")
lines.append('    __android_log_print(ANDROID_LOG_ERROR, "vkshim", "call to a Vulkan function the driver does not provide");')
lines.append("    abort();")
lines.append("}")
lines.append("")
lines.append('__attribute__((visibility("default"))) int vkshim_total(void) { return VKSHIM_COUNT; }')
lines.append("")
lines.append('__attribute__((visibility("default"))) int vkshim_bind(void *handle) {')
lines.append("    int ok = 0;")
lines.append("    for (int i = 0; i < VKSHIM_COUNT; i++) {")
lines.append("        void *p = dlsym(handle, vkshim_names[i]);")
lines.append("        if (p) ok++;")
lines.append("        vkshim_table[i] = p ? p : (void *)vkshim_missing;")
lines.append("    }")
lines.append("    return ok;")
lines.append("}")

lines.append("")
lines.append("/* If the host published the custom-driver handle, bind as soon as this library loads.")
lines.append("   This lets a copy of the shim loaded in any linker namespace set itself up. */")
lines.append("__attribute__((constructor)) static void vkshim_autobind(void) {")
lines.append('    const char *s = getenv("VKSHIM_HANDLE");')
lines.append("    if (!s) return;")
lines.append("    void *h = (void *)(uintptr_t)strtoull(s, NULL, 16);")
lines.append("    if (h) vkshim_bind(h);")
lines.append("}")

with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("generated %d stubs" % len(names))
