#!/usr/bin/env python3
"""Generates vkshim_gen.c: a library exporting every Vulkan command as a tiny
forwarding stub. The stubs jump through a table that vkshim_bind() fills in with
the functions of an already-opened Vulkan loader (the one using the custom driver)."""
import os
import re
import sys

inc, out = sys.argv[1], sys.argv[2]

names = []
seen = set()
protos = {}   # name -> (return type, [params])
for fn in ("vulkan_core.h", "vulkan_android.h"):
    path = os.path.join(inc, fn)
    if not os.path.exists(path):
        if fn == "vulkan_core.h":
            sys.exit("missing " + path)
        continue
    text = open(path, encoding="utf-8", errors="replace").read()
    for m in re.finditer(r"VKAPI_CALL\s+(vk[A-Za-z0-9_]+)\s*\(", text):
        n = m.group(1)
        if n not in seen:
            seen.add(n)
            names.append(n)
    for m in re.finditer(r"VKAPI_ATTR\s+(\w+)\s+VKAPI_CALL\s+(vk[A-Za-z0-9_]+)\s*\(([^;]*?)\)\s*;", text, re.S):
        ret, n, params = m.group(1), m.group(2), m.group(3).strip()
        plist = [] if params in ("", "void") else [p.strip() for p in params.split(",")]
        protos.setdefault(n, (ret, plist))

if len(names) < 100:
    sys.exit("only found %d Vulkan functions in %s" % (len(names), inc))

def wrappable(n):
    """VkResult commands with at most 8 register arguments (no floats, no struct by value) get a wrapper
    that logs error results. Anything else stays a plain tail-jump stub."""
    if n not in protos:
        return False
    ret, plist = protos[n]
    if ret != "VkResult" or len(plist) > 8:
        return False
    for p in plist:
        if "*" in p:
            continue
        if re.search(r"\b(float|double)\b", p):
            return False
    return True

COUNTED = {"vkQueuePresentKHR": 1, "vkQueueSubmit": 2, "vkQueueSubmit2": 2, "vkQueueSubmit2KHR": 2,
           "vkAcquireNextImageKHR": 3, "vkAcquireNextImage2KHR": 3}
PROC = ("vkGetInstanceProcAddr", "vkGetDeviceProcAddr")
wrapped = [n for n in names if wrappable(n) and n not in PROC]
wrapped_set = set(wrapped)

lines = []
lines.append("/* generated by gen_shim.py - do not edit */")
lines.append("#include <stddef.h>")
lines.append("#include <stdlib.h>")
lines.append("#include <stdint.h>")
lines.append("#include <dlfcn.h>")
lines.append("#include <android/log.h>")
lines.append("#include <string.h>")
lines.append("#include <pthread.h>")
lines.append("#include <unistd.h>")
lines.append("")
lines.append("#define VKSHIM_COUNT %d" % len(names))
lines.append("")
lines.append('__attribute__((visibility("hidden"), used)) void *vkshim_table[VKSHIM_COUNT];')
lines.append("")
lines.append("static const char *const vkshim_names[VKSHIM_COUNT] = {")
for n in names:
    lines.append('    "%s",' % n)
lines.append("};")
lines.append("")
lines.append("#define VKSHIM_STUB(off, name) \\")
lines.append('    __attribute__((naked, visibility("default"))) void name(void) { \\')
lines.append("        __asm__ volatile( \\")
lines.append('            "adrp x16, vkshim_table + " #off "\\n\\t" \\')
lines.append('            "ldr x16, [x16, :lo12:vkshim_table + " #off "]\\n\\t" \\')
lines.append('            "br x16\\n\\t"); \\')
lines.append("    }")
lines.append("")
lines.append("static volatile unsigned vkshim_cnt[4];   /* present, submit, acquire */")
lines.append("static volatile int vkshim_errs;")
lines.append("static volatile int vkshim_logger_on;")
lines.append("static void *vkshim_logger(void *a) {")
lines.append("    unsigned lp = 0, ls = 0, la = 0;")
lines.append("    for (int i = 0; i < 80; i++) {")
lines.append("        sleep(5);")
lines.append("        unsigned p = vkshim_cnt[1], s = vkshim_cnt[2], q = vkshim_cnt[3];")
lines.append('        __android_log_print(ANDROID_LOG_INFO, "GuestHost", "vkshim: last 5 s: presents=%u submits=%u acquires=%u (totals %u/%u/%u)", p - lp, s - ls, q - la, p, s, q);')
lines.append("        lp = p; ls = s; la = q;")
lines.append("    }")
lines.append("    return NULL;")
lines.append("}")
lines.append("static void vkshim_after(int idx, int res, int kind) {")
lines.append("    if (kind) {")
lines.append("        unsigned c = __sync_add_and_fetch(&vkshim_cnt[kind], 1);")
lines.append("        if (c == 1 && !__sync_lock_test_and_set(&vkshim_logger_on, 1)) {")
lines.append("            pthread_t t; if (pthread_create(&t, NULL, vkshim_logger, NULL) == 0) pthread_detach(t);")
lines.append("        }")
lines.append("        if (c <= 3) __android_log_print(ANDROID_LOG_INFO, \"GuestHost\", \"vkshim: %s call #%u -> %d\", vkshim_names[idx], c, res);")
lines.append("    }")
lines.append("    if (res < 0 && vkshim_errs < 200) {")
lines.append("        vkshim_errs++;")
lines.append('        __android_log_print(ANDROID_LOG_ERROR, "vkshim", "%s returned %d", vkshim_names[idx], res);')
lines.append("    }")
lines.append("}")
lines.append("typedef long (*vkshim_f8)(long, long, long, long, long, long, long, long);")
lines.append("typedef void *(*vkshim_gpa)(long, const char *);")
lines.append("")
idx = {n: i for i, n in enumerate(names)}
for i, n in enumerate(names):
    if n in wrapped_set:
        lines.append("__attribute__((visibility(\"default\"))) long %s(long a0, long a1, long a2, long a3, long a4, long a5, long a6, long a7) {" % n)
        lines.append("    long r = ((vkshim_f8)vkshim_table[%d])(a0, a1, a2, a3, a4, a5, a6, a7);" % i)
        lines.append("    vkshim_after(%d, (int)r, %d);" % (i, COUNTED.get(n, 0)))
        lines.append("    return r;")
        lines.append("}")
    elif n in PROC:
        pass   # defined below, after the wrapper table exists
    else:
        lines.append("VKSHIM_STUB(%d, %s)" % (i * 8, n))
lines.append("")
# table of wrapper addresses, so vkGet*ProcAddr hands out the wrappers and not the driver's raw functions
lines.append("__attribute__((visibility(\"default\"))) void *vkGetInstanceProcAddr(long, const char *);")
lines.append("__attribute__((visibility(\"default\"))) void *vkGetDeviceProcAddr(long, const char *);")
lines.append("static void *const vkshim_wrap[VKSHIM_COUNT] = {")
for n in names:
    lines.append("    %s," % ("(void *)" + n if (n in wrapped_set or n in PROC) and n in names else "0"))
lines.append("};")
lines.append("static void *vkshim_lookup(const char *n, void *real) {")
lines.append("    if (!real || !n) return real;")
lines.append("    for (int i = 0; i < VKSHIM_COUNT; i++)")
lines.append("        if (vkshim_wrap[i] && !strcmp(n, vkshim_names[i])) return vkshim_wrap[i];")
lines.append("    return real;")
lines.append("}")
for n in PROC:
    if n in idx:
        lines.append("__attribute__((visibility(\"default\"))) void *%s(long a0, const char *name) {" % n)
        lines.append("    void *r = ((vkshim_gpa)vkshim_table[%d])(a0, name);" % idx[n])
        lines.append("    return vkshim_lookup(name, r);")
        lines.append("}")
lines.append("")
lines.append("static void vkshim_missing(void) {")
lines.append('    __android_log_print(ANDROID_LOG_ERROR, "vkshim", "call to a Vulkan function the driver does not provide");')
lines.append("    abort();")
lines.append("}")
lines.append("")
lines.append('__attribute__((visibility("default"))) int vkshim_total(void) { return VKSHIM_COUNT; }')
lines.append("")
lines.append('__attribute__((visibility("default"))) int vkshim_bind(void *handle) {')
lines.append("    int ok = 0;")
lines.append("    for (int i = 0; i < VKSHIM_COUNT; i++) {")
lines.append("        void *p = dlsym(handle, vkshim_names[i]);")
lines.append("        if (p) ok++;")
lines.append("        vkshim_table[i] = p ? p : (void *)vkshim_missing;")
lines.append("    }")
lines.append("    return ok;")
lines.append("}")

lines.append("")
lines.append("/* If the host published the custom-driver handle, bind as soon as this library loads.")
lines.append("   This lets a copy of the shim loaded in any linker namespace set itself up. */")
lines.append("__attribute__((constructor)) static void vkshim_autobind(void) {")
lines.append('    const char *s = getenv("VKSHIM_HANDLE");')
lines.append("    if (!s) return;")
lines.append("    void *h = (void *)(uintptr_t)strtoull(s, NULL, 16);")
lines.append("    if (h) vkshim_bind(h);")
lines.append("}")

with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("generated %d stubs, %d logging wrappers" % (len(names), len(wrapped)))
